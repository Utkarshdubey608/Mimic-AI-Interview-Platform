def test_me_reports_the_role_from_firestore(authed_client: TestClient, monkeypatch) -> None:
    from app.web.services import users

    async def _recruiter(_settings, _uid):
        return users.RECRUITER

    async def _no_name(_settings, _uid):
        return None

    monkeypatch.setattr(users, "get_role", _recruiter)
    monkeypatch.setattr(users, "get_display_name", _no_name)

