VALID_LEAD = {
    "firstName": "Ada",
    "lastName": "Lovelace",
    "email": "Ada@Example.com",
    "hiresPerYear": "10-50",
}


# ── leads (public) ────────────────────────────────────────────────────────────


@pytest.fixture
def public_client() -> TestClient:
    return TestClient(create_app())


def test_a_lead_is_stored_and_acknowledged(public_client: TestClient, fake_store) -> None:
    response = public_client.post("/api/web/leads", json=VALID_LEAD)

    assert response.status_code == 201
    assert response.json() == {"ok": True}

    stored = list(fake_store.leads.docs.values())
    assert len(stored) == 1
    assert stored[0]["email"] == "ada@example.com"   # normalised
    assert stored[0]["source"] == "mimic-site"       # defaulted
    assert stored[0]["createdAt"]
    assert stored[0]["id"]                           # generated by the store


def test_leads_needs_no_token(public_client: TestClient) -> None:
    """Visitors filling in the marketing form are pre-login."""
    assert public_client.post("/api/web/leads", json=VALID_LEAD).status_code == 201


def test_an_invalid_lead_is_rejected_and_stores_nothing(
    public_client: TestClient, fake_store
) -> None:
    response = public_client.post(
        "/api/web/leads", json={**VALID_LEAD, "email": "not-an-email"}
    )
    assert response.status_code == 422
    assert "email" in response.json()["error"]
    assert fake_store.leads.docs == {}


def test_two_leads_do_not_collide(public_client: TestClient, fake_store) -> None:
    """Ids are generated per write; the same person submitting twice is two rows."""
    public_client.post("/api/web/leads", json=VALID_LEAD)
    public_client.post("/api/web/leads", json=VALID_LEAD)
    assert len(fake_store.leads.docs) == 2


