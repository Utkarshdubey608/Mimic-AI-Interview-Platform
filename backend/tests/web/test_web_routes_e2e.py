def test_tts_token_mints_a_locked_grant(authed_client: TestClient, monkeypatch) -> None:
    """The browser connects to Google itself, so what this returns IS the whole
    session — the setup must be locked into the token, not sent by the client."""
    from datetime import datetime, timezone

    from app.providers import gemini as provider_gemini
    from app.web.routes import help as help_route

    captured: dict = {}

    class _FakeToken:
        token = "auth_tokens/abc"
        ws_url = "wss://example.invalid/live"
        model = "models/fake-live"
        expires_at = datetime(2026, 1, 1, tzinfo=timezone.utc)
        connect_by = datetime(2026, 1, 1, tzinfo=timezone.utc)

    class _FakeClient:
        def __init__(self, settings):
            self.settings = settings

        async def mint_live_token(self, setup, *, session_minutes, uses=1):
            captured["setup"] = setup
            captured["session_minutes"] = session_minutes
            captured["uses"] = uses
            return _FakeToken()

    monkeypatch.setattr(help_route, "GeminiClient", _FakeClient)

    response = authed_client.post(
        "/api/web/help/tts-token",
        json={"text": "Go to Sessions to create an interview.", "lang": "hi"},
    )
    assert response.status_code == 200

    body = response.json()
    assert body["token"] == "auth_tokens/abc"
    assert body["wsUrl"] == "wss://example.invalid/live"
    assert set(body) == {"token", "wsUrl", "model", "expiresAt", "connectBy"}

    setup = captured["setup"]
    # Audio out, nothing listening.
    assert setup["generationConfig"]["responseModalities"] == ["AUDIO"]
    # The language is pinned, and the text is inside the setup rather than sent by
    # the client — that is what the lock protects.
    instruction = setup["systemInstruction"]["parts"][0]["text"]
    assert "in Hindi" in instruction
    assert "<read>Go to Sessions to create an interview.</read>" in instruction
    # One use, bounded session: a leaked token cannot fund an open-ended chat.
    assert captured["uses"] == 1
    assert 0 < captured["session_minutes"] <= 10


